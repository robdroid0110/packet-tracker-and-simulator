/* Keyboard-only canvas checks against a temporary backend. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { spawn } = require('child_process');
const fs = require('fs'), os = require('os'), path = require('path');

(async () => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'pt-keyboard-canvas-'));
  const ready = path.join(folder, 'ready.json');
  const executable = process.env.PACKET_TRACKER_EXECUTABLE;
  const server = spawn(executable || 'python3', [
    ...(executable ? [] : ['desktop.py']), '--server', '--port', '0',
    '--state', path.join(folder, 'lab.json'), '--ready-file', ready
  ], { stdio: 'ignore' });
  let browser;
  try {
    for (let i = 0; i < 600 && !fs.existsSync(ready); i++) {
      if (server.exitCode !== null) throw Error('Isolated server exited');
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    if (!fs.existsSync(ready)) throw Error('Isolated server did not start');
    const url = 'http://127.0.0.1:' + JSON.parse(fs.readFileSync(ready)).port;
    const command = async text => {
      const response = await fetch(url + '/api/command', {method:'POST',
        headers:{'content-type':'application/json'}, body:JSON.stringify({command:text})});
      const value = await response.json();
      if (!value.ok) throw Error(text + ': ' + value.output);
      return value;
    };
    const state = async () => (await (await fetch(url + '/api/state')).json());
    for (const text of ['add router R1 120 140', 'add switch SW1 400 140', 'add pc PC1 400 300']) await command(text);
    browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM || '/usr/bin/chromium',args:['--no-sandbox']});
    const page = await browser.newPage({viewport:{width:1440,height:900}});
    page.setDefaultTimeout(7000);
    await page.goto(url);
    await page.locator('#nodes .node').first().waitFor();
    await page.waitForFunction(() => document.querySelectorAll('#nodes .node[role="button"]').length === 3);
    const nodes = page.locator('#nodes .node');
    if (await nodes.locator('[tabindex="0"]').count()) throw Error('Unexpected nested node controls');
    if (await page.locator('#nodes .node[tabindex="0"]').count() !== 1) throw Error('Canvas has more than one Tab stop');
    const r1 = page.locator('#nodes .node[data-name="R1"]');
    if (!(await r1.getAttribute('aria-label')).includes('R1') || !await r1.getAttribute('aria-describedby')) throw Error('Missing device accessible name or instructions');
    const session = await page.context().newCDPSession(page);
    const ax = await session.send('Accessibility.getFullAXTree');
    if (!ax.nodes.some(node => node.role?.value === 'button' && node.name?.value?.includes('R1'))) throw Error('Device absent from Chromium accessibility tree');
    await page.keyboard.press('Shift+D');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.evaluate(() => document.body.classList.add('pt-high-contrast'));
    const outline=await page.evaluate(() => ({style:getComputedStyle(document.activeElement).outlineStyle,color:getComputedStyle(document.activeElement).outlineColor}));
    if(outline.style==='none'||outline.color!=='rgb(255, 255, 0)')throw Error('Focused device is not visible in high contrast');
    await page.evaluate(() => document.body.classList.remove('pt-high-contrast'));
    await page.emulateMedia({forcedColors:'active'});
    if(await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle)==='none')throw Error('Focused device is not visible in forced colors');
    await page.emulateMedia({forcedColors:'none'});
    await page.keyboard.press('Tab');
    if (await page.evaluate(() => !!document.activeElement?.closest('#nodes'))) throw Error('Tab did not leave the device group');
    await page.keyboard.press('Shift+Tab');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'SW1');
    await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => state.devices.SW1.x === 410);
    if ((await state()).devices.SW1.x !== 410) throw Error('Keyboard move did not reach backend');
    if (await page.evaluate(() => document.activeElement?.dataset.name) !== 'SW1') throw Error('Focus lost after moving');
    await page.keyboard.press('Control+Shift+ArrowDown');
    await page.waitForFunction(() => state.devices.SW1.y === 190);
    await page.keyboard.press('Control+z');
    await page.waitForFunction(() => state.devices.SW1.y === 140);
    await page.keyboard.press('Control+y');
    await page.waitForFunction(() => state.devices.SW1.y === 190);
    for (let i=0; i<3; i++) await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => state.devices.SW1.x === 440);
    if ((await state()).devices.SW1.x !== 440) throw Error('Rapid keyboard movement lost an update');
    await page.keyboard.press('Shift+ArrowRight');
    await page.keyboard.press('ArrowDown');
    await page.waitForFunction(() => state.devices.SW1.x === 450);
    if (await page.evaluate(() => document.activeElement?.dataset.name) !== 'PC1') throw Error('Move response stole focus from another device');
    await page.keyboard.press('ArrowUp');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'SW1');
    await page.evaluate(() => command('show links',false));
    if (await page.evaluate(() => document.activeElement?.dataset.name) !== 'SW1') throw Error('Focus lost on topology refresh');
    const popup = page.waitForEvent('popup');
    await page.keyboard.press('Enter');
    const child = await popup;
    await child.locator('#dialogTabs').waitFor();
    if (await child.locator('#workspaceShell').isVisible()) throw Error('Device window includes main workspace');
    await child.close();await page.bringToFront();
    await page.keyboard.press('Shift+D');
    await page.locator('[data-category="connections"]').focus();
    await page.keyboard.press('Enter');
    await page.locator('[data-connection="auto"]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'SW1');
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowDown');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'PC1');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => state.links.some(l => l.a_device === 'SW1' && l.b_device === 'PC1'));
    if ((await state()).links.length !== 1) throw Error('Auto connection not saved');
    await page.locator('[data-connection="copper-straight"]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'PC1');
    await page.keyboard.press('ArrowUp'); // SW1
    await page.keyboard.press('ArrowUp'); // R1
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.closest('#ptPortDialog'));
    await page.keyboard.press('Shift+d');
    if (!await page.evaluate(() => !!document.activeElement?.closest('#ptPortDialog'))) throw Error('Canvas shortcut escaped the interface picker');
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.locator('[data-connection="copper-straight"]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.closest('#ptPortDialog'));
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'R1');
    await page.keyboard.press('ArrowDown');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'SW1');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.closest('#ptPortDialog'));
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => state.links.length === 2);
    if ((await state()).links.length !== 2) throw Error('Manual keyboard connection not saved');
    if (await page.evaluate(() => document.activeElement?.dataset.name) !== 'SW1') throw Error('Focus lost after manual connection');
    await command('add pc "My Host" 100 520');
    await command("add switch 'Odd'\\''One' 360 520");
    await page.evaluate(() => fetchState());
    const quoted = page.locator('#nodes .node[data-name="My Host"]');
    await quoted.focus();
    await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => state.devices['My Host'].x === 110);
    await page.locator('[data-connection="auto"]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'My Host');
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(() => document.activeElement?.dataset.name === "Odd'One");
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => state.links.some(link => link.a_device === 'My Host' && link.b_device === "Odd'One"));
    if (!(await state()).links.some(link => link.a_device === 'My Host' && link.b_device === "Odd'One")) throw Error('Quoted device names were not connected');
    await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => state.devices["Odd'One"].x === 370);
    await command('add pc Overlap 110 520');
    await page.evaluate(() => fetchState());
    await page.locator('#nodes .node[data-name="My Host"]').focus();
    await page.keyboard.press('Control+ArrowRight');
    await page.keyboard.press('Control+ArrowRight');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'Overlap');
    await page.keyboard.press('Shift+ArrowDown');
    await page.waitForFunction(() => state.devices.Overlap.y === 530);
    if ((await state()).devices['My Host'].y !== 520) throw Error('Moving one overlapping device moved the other');
    await command('add router "Router One" 100 650');
    await command("add router 'Router'\\''Two' 360 650");
    await page.evaluate(() => fetchState());
    await page.locator('#nodes .node[data-name="Router One"]').focus();
    await page.locator('[data-connection="copper-straight"]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'Router One');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.closest('#ptPortDialog'));
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'Router One');
    await page.keyboard.press('Control+ArrowRight');
    await page.waitForFunction(() => document.activeElement?.dataset.name === "Router'Two");
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.closest('#ptPortDialog'));
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => state.links.some(link => link.a_device === 'Router One' && link.b_device === "Router'Two"));
    await page.keyboard.press('Shift+w');
    await page.waitForFunction(() => document.activeElement?.id === 'wlSearch');
    await page.keyboard.press('Tab');
    if (await page.evaluate(() => document.activeElement?.id) !== 'wlAdd') throw Error('Workspace List add button is not reachable by Tab');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.activeElement?.id === 'wlName');
    await page.keyboard.press('Control+a');
    await page.keyboard.type('KeyAdded');
    if (await page.evaluate(() => document.activeElement?.id) !== 'wlName') throw Error('Canvas shortcut interfered with text entry');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => !!state.devices.KeyAdded);
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => document.activeElement?.dataset.name === "Router'Two");
    await command('add pc FarAway 3500 650');
    await page.evaluate(() => fetchState());
    for(let i=0;i<15 && await page.evaluate(() => document.activeElement?.dataset.name) !== 'FarAway';i++){
      await page.keyboard.press('Control+ArrowRight');
    }
    await page.waitForFunction(() => document.activeElement?.dataset.name === 'FarAway');
    await page.waitForFunction(() => {
      const node=document.activeElement.getBoundingClientRect(),work=document.querySelector('#workspace').getBoundingClientRect();
      return node.left>=work.left && node.right<=work.right-16 && node.top>=work.top && node.bottom<=work.bottom-16;
    });
    await page.evaluate(() => setZoom(1.5));
    await page.waitForFunction(() => {
      const node=document.activeElement.getBoundingClientRect(),work=document.querySelector('#workspace').getBoundingClientRect();
      return document.activeElement?.dataset.name==='FarAway' && node.left>=work.left && node.right<=work.right-16 && node.top>=work.top && node.bottom<=work.bottom-16;
    });
    await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => state.devices.FarAway.x === 3510);
    await command('cluster add Hidden R1');
    await page.evaluate(() => fetchState());
    if (await page.locator('#nodes .node[data-name="R1"]').isVisible()) throw Error('Clustered device should be hidden in root');
    if (await page.locator('#nodes .node[data-name="R1"]').getAttribute('tabindex') !== '-1') throw Error('Hidden device remains in the tab order');
    await page.waitForTimeout(100);
    await page.evaluate(() => {
      document.querySelector('.workspace-scrollbar.horizontal').scrollLeft=10000;
      document.querySelector('.workspace-scrollbar.vertical').scrollTop=10000;
    });
    await page.waitForFunction(() => window.ptPan.x===0 && window.ptPan.y===0);
    const sw=await page.locator('#nodes .node[data-name="SW1"]').boundingBox();
    await page.mouse.move(sw.x+20,sw.y+20);await page.mouse.down();
    await page.mouse.move(sw.x+50,sw.y+20);await page.mouse.up();
    await page.waitForFunction(() => state.devices.SW1.x === 470);
    await page.waitForTimeout(100);
    if(await page.evaluate(() => window.ptPan.x!==0 || window.ptPan.y!==0))throw Error('Pointer drag unexpectedly panned to the keyboard-focused device');
    await page.locator('.workspace-tab').nth(1).focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#nodes')).display==='none');
    await page.keyboard.press('Shift+d');
    if(await page.evaluate(() => !!document.activeElement?.closest('#nodes')))throw Error('Physical mode focused a hidden logical device');
    await page.keyboard.press('Shift+l');
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#nodes')).display!=='none');
    await page.keyboard.press('Shift+d');
    if(!await page.evaluate(() => !!document.activeElement?.closest('#nodes')))throw Error('Logical mode did not restore device keyboard access');
    console.log('PASS: keyboard navigation, movement/undo, device windows, automatic/manual links, overlapping devices, workspace list, pan, clusters and ARIA');
  } finally {
    if (browser) await browser.close();
    if (server.exitCode === null) { server.kill('SIGTERM'); await new Promise(resolve => server.once('exit', resolve)); }
    fs.rmSync(folder, {recursive:true,force:true});
  }
})().catch(error => {console.error(error);process.exitCode=1});
