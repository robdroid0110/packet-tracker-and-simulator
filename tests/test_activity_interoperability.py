"""Regression for user-owned activity imports and experimental PKT network exports.

All fixtures are original synthetic XML generated by this project. No teacher
content, vendor artwork, saved credentials, or third-party lesson files shipped.
"""
import base64
from copy import deepcopy
from pathlib import Path
import os
import tempfile
import unittest
from xml.etree import ElementTree as ET

from netsim.model import LabError, NetworkLab
from netsim.lab_import import import_pkt,decode_file
from netsim.pkt_export import export_pkt
from netsim.pkt_codec.pt_crypto import encrypt_pkt,decrypt_pkt
from netsim.activity import progress,validate_activity


class ActivityImportTests(unittest.TestCase):
    @staticmethod
    def base():
        n=NetworkLab()
        n.add_device('router','R1',220,110)
        n.add_device('switch','SW1',340,220)
        n.add_device('pc','PC1',460,300)
        n.connect('R1','g0/0','SW1','fa0/1')
        n.connect('SW1','fa0/2','PC1','eth0')
        n.set_ip('R1','g0/0','192.0.2.1/24')
        n.set_ip('PC1','eth0','192.0.2.10/24')
        n.set_gateway('PC1','192.0.2.1')
        return n

    def synthetic_activity(self):
        data,_=export_pkt(self.base())
        first=ET.fromstring(decrypt_pkt(data))
        initial=deepcopy(first)
        answer=deepcopy(first)
        for e in answer.findall('.//RUNNINGCONFIG/LINE'):
            if e.text=='ip address 192.0.2.1 255.255.255.0':
                e.text='ip address 192.0.2.254 255.255.255.0'
                break
        root=ET.Element('PACKETTRACER5_ACTIVITY')
        ET.SubElement(root,'VERSION').text='9.0.0.0810'
        root.extend([first,initial,answer])
        comparisons=ET.SubElement(root,'COMPARISONS')
        ET.SubElement(comparisons,'NODE')
        activity=ET.SubElement(root,'ACTIVITY')
        instructions=ET.SubElement(activity,'INSTRUCTIONS')
        ET.SubElement(instructions,'PAGE',{'title':'Step 1'}).text='<h2>Configure gateway</h2><script>alert(1)</script><p>Set R1 interface to .254</p>'
        ET.SubElement(instructions,'PAGE',{'title':'Step 2'}).text='<p>Verify the link</p>'
        return encrypt_pkt(ET.tostring(root,encoding='utf-8'))

    def test_pkt_encode_decode_roundtrip_network(self):
        original=self.base()
        encoded,warnings=export_pkt(original)
        self.assertTrue(warnings)
        self.assertTrue(encoded)
        decoded=decrypt_pkt(encoded)
        self.assertTrue(decoded.startswith(b'<?xml'))
        recovered,iw=import_pkt(encoded)
        self.assertEqual(len(recovered.devices),3)
        self.assertEqual(len(recovered.links),2)
        self.assertEqual(recovered.devices['PC1'].interfaces['eth0'].ip,'192.0.2.10/24')
        self.assertIsNone(recovered.activity)

    def test_synthetic_pka_import_instructions_and_checks(self):
        encoded=self.synthetic_activity()
        lab,warnings=import_pkt(encoded,filename='Demo CCNA.pka')
        self.assertEqual((len(lab.devices),len(lab.links)),(3,2))
        self.assertEqual(len(lab.activity['pages']),2)
        self.assertEqual(lab.activity['title'],'Demo CCNA')
        self.assertNotIn('alert(1)',lab.activity['pages'][0]['text'])
        self.assertIn('Configure gateway',lab.activity['pages'][0]['text'])
        self.assertTrue(any('NOT supported' in w for w in warnings))
        self.assertGreater(len(lab.activity['checks']),0)
        self.assertFalse(any('192.0.2.254' in str(v) for v in lab.activity['checks']))
        p=progress(lab)
        self.assertLess(p['supported_passed'],p['supported_checks'])
        lab.set_ip('R1','g0/0','192.0.2.254/24')
        self.assertGreater(progress(lab)['supported_passed'],p['supported_passed'])

    def test_pka_activity_persists_in_native_json(self):
        lab,_=import_pkt(self.synthetic_activity(),filename='Demo CCNA.pka')
        lab.activity['completed_pages']=[0,1]
        with tempfile.TemporaryDirectory() as folder:
            p=Path(folder)/'test.json'
            lab.save(str(p))
            restored=NetworkLab()
            restored.load(str(p))
            self.assertEqual(progress(restored)['reviewed_pages'],2)
            self.assertEqual(len(restored.links),2)
            restored.reset()
            self.assertIsNone(restored.activity)

    def test_validation_rejects_forged_activity(self):
        with self.assertRaises(LabError):
            validate_activity({'type':'other','pages':[]})
        with self.assertRaises(LabError):
            validate_activity({'type':'imported_pka','title':'Hi','source_version':'9',
                               'pages':[{'title':'One','text':'Okay'}],
                               'completed_pages':[7],'checks':[],'vendor_criterion_count':0})

    def test_rejects_xml_external_entities(self):
        payload=encrypt_pkt(b'<!DOCTYPE x [<!ENTITY x SYSTEM "file:///etc/passwd">]><PACKETTRACER5/>')
        with self.assertRaisesRegex(ValueError,'External entity'):
            import_pkt(payload)

    @unittest.skipUnless(os.environ.get('PTS_TEST_PKA'),
                         'Use an explicitly supplied private local PKA fixture')
    def test_real_activity_private_opt_in(self):
        p=Path(os.environ['PTS_TEST_PKA'])
        lab,warnings=decode_file(base64.b64encode(p.read_bytes()).decode(),p.name)
        self.assertTrue(lab.activity)
        self.assertTrue(lab.activity['pages'])
        self.assertGreater(len(lab.links),0)
        self.assertTrue(warnings)


if __name__=='__main__':
    unittest.main()
